// Front matter (a deliberately small YAML subset: flat keys, scalars, inline or dashed lists)

pub fn split_frontmatter(text: &str) -> Option<(&str, &str)> {
    let t = text.strip_prefix('\u{feff}').unwrap_or(text);
    let rest = t.strip_prefix("---\n").or_else(|| t.strip_prefix("---\r\n"))?;
    let mut idx = 0;
    for line in rest.split_inclusive('\n') {
        let trimmed = line.trim_end();
        if trimmed == "---" || trimmed == "..." {
            return Some((&rest[..idx], &rest[idx + line.len()..]));
        }
        idx += line.len();
    }
    None
}

pub fn parse_fm(fm: &str) -> Vec<(String, FmValue)> {
    let mut out: Vec<(String, FmValue)> = Vec::new();
    let mut open: Option<usize> = None; // last key with an empty inline value (list or block scalar)
    let mut block = false;
    for raw in fm.lines() {
        let t = raw.trim();
        if t.is_empty() || t.starts_with('#') {
            continue;
        }
        let indented = raw.starts_with(' ') || raw.starts_with('\t');
        if let Some(i) = open {
            if t.starts_with("- ") || t == "-" {
                let item = unquote(t.trim_start_matches('-').trim());
                if let FmValue::List(l) = &mut out[i].1 {
                    l.push(item);
                    continue;
                }
            }
            if indented {
                match &mut out[i].1 {
                    FmValue::Str(s) => {
                        if !s.is_empty() {
                            s.push(if block { '\n' } else { ' ' });
                        }
                        s.push_str(t);
                    }
                    FmValue::List(l) if l.is_empty() => out[i].1 = FmValue::Str(t.to_string()),
                    FmValue::List(_) => {}
                }
                continue;
            }
        }
        let Some((k, v)) = t.split_once(':') else { continue };
        let key = k.trim().to_string();
        let v = v.trim();
        open = None;
        block = false;
        if v.is_empty() {
            out.push((key, FmValue::List(Vec::new())));
            open = Some(out.len() - 1);
        } else if v.starts_with('[') && v.ends_with(']') {
            out.push((key, FmValue::List(split_inline_list(&v[1..v.len() - 1]))));
        } else if matches!(v, "|" | "|-" | ">" | ">-") {
            out.push((key, FmValue::Str(String::new())));
            open = Some(out.len() - 1);
            block = v.starts_with('|');
        } else {
            out.push((key, FmValue::Str(unquote(v))));
        }
    }
    out
}

pub fn split_inline_list(s: &str) -> Vec<String> {
    let mut items = Vec::new();
    let mut cur = String::new();
    let mut quote: Option<char> = None;
    for c in s.chars() {
        match (quote, c) {
            (None, '"' | '\'') => {
                quote = Some(c);
                cur.push(c);
            }
            (Some(q), c) if c == q => {
                quote = None;
                cur.push(c);
            }
            (None, ',') => {
                items.push(std::mem::take(&mut cur));
            }
            _ => cur.push(c),
        }
    }
    items.push(cur);
    items.into_iter().map(|x| unquote(x.trim())).filter(|x| !x.is_empty()).collect()
}

fn unquote(s: &str) -> String {
    let s = s.trim();
    if s.len() >= 2 && s.starts_with('"') && s.ends_with('"') {
        return s[1..s.len() - 1].replace("\\\"", "\"").replace("\\\\", "\\");
    }
    if s.len() >= 2 && s.starts_with('\'') && s.ends_with('\'') {
        return s[1..s.len() - 1].replace("''", "'");
    }
    // strip trailing comments (" # ...") on plain scalars
    match s.find(" #") {
        Some(i) => s[..i].trim_end().to_string(),
        None => s.to_string(),
    }
}

fn needs_quotes(s: &str) -> bool {
    s.is_empty()
        || s != s.trim()
        || s.contains(": ")
        || s.contains(" #")
        || s.ends_with(':')
        || s.starts_with(['-', '?', ':', ',', '[', ']', '{', '}', '#', '&', '*', '!', '|', '>', '\'', '"', '%', '@', '`'])
        || matches!(s.to_lowercase().as_str(), "true" | "false" | "null" | "yes" | "no" | "~" | "on" | "off")
}

fn fm_scalar(s: &str) -> String {
    let s = s.replace(['\r', '\n'], " ");
    if needs_quotes(&s) { format!("\"{}\"", s.replace('\\', "\\\\").replace('"', "\\\"")) } else { s }
}

fn fm_list_item(s: &str) -> String {
    let s = s.replace(['\r', '\n'], " ");
    let s = s.as_str();
    if needs_quotes(s) || s.contains([',', '[', ']']) {
        format!("\"{}\"", s.replace('\\', "\\\\").replace('"', "\\\""))
    } else {
        s.to_string()
    }
}

