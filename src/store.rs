pub const DECISION_STATUSES: &[&str] = &["proposed", "accepted", "superseded", "deprecated", "rejected"];
pub const INDEX_START: &str = "<!-- kontext:index:start — generated by kontext; edits between these markers are overwritten -->";
pub const INDEX_END: &str = "<!-- kontext:index:end -->";

#[derive(Debug, Clone, PartialEq)]
pub enum FmValue {
    Str(String),
    List(Vec<String>),
}

impl FmValue {
    pub fn as_str(&self) -> String {
        match self {
            FmValue::Str(s) => s.clone(),
            FmValue::List(l) => l.join(", "),
        }
    }
    pub fn as_list(&self) -> Vec<String> {
        match self {
            FmValue::Str(s) => split_inline_list(s),
            FmValue::List(l) => l.clone(),
        }
    }
}

#[derive(Debug, Clone, Default)]
pub struct Entry {
    pub id: String,
    pub kind: String,
    pub title: String,
    pub status: Option<String>,
    pub date: Option<String>,
    /// When someone should look at the entry again (`YYYY-MM-DD`). A review date, not an expiry:
    /// past it the entry is marked, never hidden.
    pub review_by: Option<String>,
    /// When someone last confirmed the entry still holds: a day (`YYYY-MM-DD`) or, as `kontext
    /// confirm` writes it, a UTC second (`YYYY-MM-DDTHH:MM:SSZ`). Freshness and drift count changes
    /// from here, as they do from an edit of the entry's own file.
    pub checked: Option<String>,
    /// How to check the entry still holds: one shell command run from the repository root by
    /// `kontext verify`, whose outcome lands in the verification ledger.
    pub verify: Option<String>,
    pub summary: Option<String>,
    pub tags: Vec<String>,
    pub paths: Vec<String>,
    pub supersedes: Vec<String>,
    pub superseded_by: Vec<String>,
    pub commits: Vec<String>,
    pub author: Option<String>,
    pub visibility: Option<String>,
    pub origin: Option<String>,
    pub extra: Vec<(String, FmValue)>,
    pub body: String,
    pub rel_path: String,
    pub style: Style,
    /// The status the file itself states (normalized). `status` is the effective one: load marks an
    /// entry superseded when an active entry names it in `supersedes`, whatever its file says.
    pub file_status: Option<String>,
    /// Load derived `superseded` from a successor's `supersedes` while the file says otherwise: a
    /// one-sided supersession that `kontext repair` writes into the file.
    pub derived_superseded: bool,
    /// Successor ids load added to `superseded_by` that the file does not list.
    pub derived_by: Vec<String>,
    /// What the parser could not read, or read as something other than it says.
    pub parse_issues: Vec<(Level, String)>,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
pub enum Level {
    /// Worth knowing, never a failure: a premise that changed under an entry.
    Info,
    Warn,
    Error,
}

#[derive(Debug, Clone)]
pub struct Issue {
    pub level: Level,
    pub path: String,
    pub msg: String,
}

impl std::fmt::Display for Issue {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        let lvl = match self.level {
            Level::Info => "info",
            Level::Error => "error",
            Level::Warn => "warn",
        };
        write!(f, "{lvl}: {}: {}", self.path, self.msg)
    }
}

impl Entry {
    pub fn get_extra(&self, key: &str) -> Option<String> {
        self.extra.iter().find(|(k, _)| k == key).map(|(_, v)| v.as_str())
    }

    pub fn set_extra(&mut self, key: &str, value: FmValue) {
        if let Some(slot) = self.extra.iter_mut().find(|(k, _)| k == key) {
            slot.1 = value;
        } else {
            self.extra.push((key.to_string(), value));
        }
    }

    /// The review date has passed (`today` is `YYYY-MM-DD`). Only active entries are due.
    pub fn review_due(&self, today: &str) -> bool {
        self.is_active() && self.review_by.as_deref().and_then(|r| r.get(..10)).is_some_and(|r| r < today)
    }

    pub fn is_active(&self) -> bool {
        !matches!(self.status.as_deref(), Some("superseded" | "deprecated" | "rejected"))
    }

    /// Active by what the file itself says, before load derived anything from successors.
    pub fn file_active(&self) -> bool {
        let own = if self.derived_superseded { self.file_status.as_deref() } else { self.status.as_deref() };
        !matches!(own, Some("superseded" | "deprecated" | "rejected"))
    }

    /// The status the canonical writer puts in the file: what the file said, never a derived one.
    fn written_status(&self) -> Option<String> {
        if self.derived_superseded { self.file_status.clone() } else { self.status.clone() }
    }

    fn written_superseded_by(&self) -> Vec<String> {
        self.superseded_by.iter().filter(|s| !self.derived_by.contains(s)).cloned().collect()
    }

    /// `0002` for sequentially numbered ADRs, otherwise the full id.
    pub fn short_id(&self) -> String {
        let digits: String = self.id.chars().take_while(|c| c.is_ascii_digit()).collect();
        let dated = self.id.get(..10).is_some_and(|d| chrono::NaiveDate::parse_from_str(d, "%Y-%m-%d").is_ok());
        if !dated && (3..=5).contains(&digits.len()) && self.id[digits.len()..].starts_with('-') {
            return digits;
        }
        self.id.clone()
    }

    /// One-line summary: explicit `summary`, else the first paragraph of `## Decision`, else of the body.
    pub fn summary_text(&self, max: usize) -> String {
        if let Some(s) = self.summary.as_ref().filter(|s| !s.trim().is_empty()) {
            return util::truncate_chars(&util::one_line(s), max);
        }
        for heading in ["## Decision", "## Summary", "## Overview", "## Purpose"] {
            if let Some(pos) = self.body.find(heading) {
                let after = &self.body[pos + heading.len()..];
                let after = after.split_once('\n').map(|(_, r)| r).unwrap_or("");
                let p = util::first_paragraph(after, max);
                if !p.is_empty() && !p.starts_with("_Pending") {
                    return p;
                }
            }
        }
        let p = util::first_paragraph(&self.body, max);
        if p.starts_with("_Pending") || p.starts_with("Pending:") { String::new() } else { p }
    }

    /// What the entry says to do: the first paragraph of `## Decision` when there is one, else the
    /// summary. A summary often states the goal and leaves the rule itself out ("error pages are no
    /// content" versus "reject them and try the next engine"), and the rule is what a change is checked against.
    pub fn rule_text(&self, max: usize) -> String {
        if let Some(pos) = self.body.find("## Decision") {
            let after = &self.body[pos + "## Decision".len()..];
            let after = after.split_once('\n').map(|(_, r)| r).unwrap_or("");
            let p = util::first_paragraph(after, max);
            if !p.is_empty() && !p.starts_with("_Pending") {
                return p;
            }
        }
        self.summary_text(max)
    }

    pub fn l0(&self, max: usize) -> String {
        let s = self.summary_text(max);
        if s.is_empty() { self.title.clone() } else { format!("{} — {}", self.title, s) }
    }

    pub fn markdown(&self) -> String {
        match self.style {
            Style::Frontmatter => self.to_frontmatter_md(),
            Style::Fields => self.to_fields_md(),
        }
    }

    fn fm_pairs(&self) -> Vec<(String, FmValue)> {
        let mut v: Vec<(String, FmValue)> = Vec::new();
        let mut s = |k: &str, val: &Option<String>| {
            if let Some(x) = val.as_ref().filter(|x| !x.is_empty()) {
                v.push((k.into(), FmValue::Str(x.clone())));
            }
        };
        s("id", &Some(self.id.clone()));
        s("kind", &Some(self.kind.clone()));
        s("title", &Some(self.title.clone()));
        s("status", &self.written_status());
        s("date", &self.date);
        s("review_by", &self.review_by);
        s("checked", &self.checked);
        s("verify", &self.verify);
        s("summary", &self.summary);
        let mut l = |k: &str, val: &Vec<String>| {
            if !val.is_empty() {
                v.push((k.into(), FmValue::List(val.clone())));
            }
        };
        l("tags", &self.tags);
        l("paths", &self.paths);
        l("supersedes", &self.supersedes);
        l("superseded_by", &self.written_superseded_by());
        l("commits", &self.commits);
        let mut s2 = |k: &str, val: &Option<String>| {
            if let Some(x) = val.as_ref().filter(|x| !x.is_empty()) {
                v.push((k.into(), FmValue::Str(x.clone())));
            }
        };
        s2("author", &self.author);
        s2("visibility", &self.visibility);
        s2("origin", &self.origin);
        v.extend(self.extra.iter().cloned());
        v
    }

    fn to_frontmatter_md(&self) -> String {
        let mut out = String::from("---\n");
        for (k, v) in self.fm_pairs() {
            match v {
                FmValue::Str(s) => out.push_str(&format!("{k}: {}\n", fm_scalar(&s))),
                FmValue::List(l) => out.push_str(&format!("{k}: [{}]\n", l.iter().map(|x| fm_list_item(x)).collect::<Vec<_>>().join(", "))),
            }
        }
        out.push_str("---\n\n");
        out.push_str(self.body.trim_start_matches('\n'));
        if !out.ends_with('\n') {
            out.push('\n');
        }
        out
    }

    fn to_fields_md(&self) -> String {
        let short = self.short_id();
        let heading = if short != self.id { format!("# {short} — {}", self.title) } else { format!("# {}", self.title) };
        let mut out = format!("{heading}\n\n");
        let mut field = |k: &str, v: String| {
            if !v.is_empty() {
                out.push_str(&format!("**{k}:** {}\n", v.replace(['\r', '\n'], " ")));
            }
        };
        field("Status", self.written_status().unwrap_or_default());
        field("Date", self.date.clone().unwrap_or_default());
        field("Review by", self.review_by.clone().unwrap_or_default());
        field("Checked", self.checked.clone().unwrap_or_default());
        field("Verify", self.verify.clone().unwrap_or_default());
        field("Summary", self.summary.clone().unwrap_or_default());
        field("Tags", self.tags.join(", "));
        field("Paths", self.paths.join(", "));
        field("Supersedes", self.supersedes.join(", "));
        field("Superseded by", self.written_superseded_by().join(", "));
        field("Commits", self.commits.join(", "));
        field("Author", self.author.clone().unwrap_or_default());
        let mut metadata = serde_json::Map::new();
        if let Some(origin) = &self.origin {
            metadata.insert("origin".into(), serde_json::json!(origin));
        }
        if let Some(visibility) = &self.visibility {
            metadata.insert("visibility".into(), serde_json::json!(visibility));
        }
        for (key, value) in &self.extra {
            metadata.insert(
                key.clone(),
                match value {
                    FmValue::Str(s) => serde_json::json!(s),
                    FmValue::List(v) => serde_json::json!(v),
                },
            );
        }
        if !metadata.is_empty() {
            field("Kontext metadata", serde_json::Value::Object(metadata).to_string());
        }
        out.push('\n');
        out.push_str(self.body.trim_start_matches('\n'));
        if !out.ends_with('\n') {
            out.push('\n');
        }
        out
    }
}

